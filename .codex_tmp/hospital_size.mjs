import fs from 'node:fs/promises';
import {Workbook,SpreadsheetFile} from '@oai/artifact-tool';
const d=JSON.parse(await fs.readFile('.codex_tmp/hospital_size.json','utf8'));
const out='D:/Hospital_Pharmacy program/outputs/hospital_size_20260908';
await fs.mkdir(out,{recursive:true});
const w=Workbook.create(),s=w.worksheets.add(d.sheet);
s.getRange('A1').write(d.rows);
for(const [k,v] of Object.entries(d.widths)) s.getRangeByIndexes(0,+k,d.rows.length,1).format.columnWidth=v;
await fs.writeFile('.codex_tmp/hospital_before.png',new Uint8Array(await (await w.render({sheetName:d.sheet,range:'R1:V5',scale:1})).arrayBuffer()));
if(process.argv.includes('--preview')) process.exit(0);
s.getRange('W1').values=[['size']];
s.getRange(`W2:W${d.rows.length}`).values=d.sizes.map(x=>[x]);
s.getRange(`W1:W${d.rows.length}`).format.columnWidth=18;
s.getRange(`W2:W${d.rows.length}`).setNumberFormat('#,##0.00');
const q=w.worksheets.add('面积汇总');
q.getRange('A1:B12').values=[['统计项目','结果'],['总记录数',d.stats.total],['有效边界记录数',null],['缺失边界记录数',d.stats.missing],['无效边界记录数',d.stats.invalid],['平均占地面积（平方米）',null],['平均占地面积（亩）',null],['size 单位','平方米'],['计算方法','原始经纬度边界按 WGS84 椭球测算多边形面积，取绝对值。'],['坐标系说明','原表未注明坐标系，未实施坐标转换；结果为近似占地面积。'],['统计范围','仅对有有效边界的记录求算术平均；缺失值留空，不按零计入。'],['指标解释','边界所包围的占地面积，不代表建筑面积、床位数或全部医院平均规模。']];
q.getRange('A13:B14').values=[['数据来源','baidu_maps_hospital_202608_sample.xls，sheet1，boundary'],['方法文档','https://pyproj4.github.io/pyproj/stable/api/geod.html']];
q.getRange('B3').formulas=[[`=COUNT('sheet1'!W2:W994)`]];
q.getRange('B6').formulas=[[`=AVERAGE('sheet1'!W2:W994)`]];
q.getRange('B7').formulas=[['=B6*15/10000']];
q.getRange('B6:B7').setNumberFormat('#,##0.00');
q.getRange('A1:A14').format.columnWidth=29;
q.getRange('B1:B14').format.columnWidth=90;
q.getRange('A1:B14').format.rowHeight=30;
q.getRange('A1:B14').format.wrapText=true;
q.getRange('A1:B1').format.font.bold=true;
if(Math.abs(q.getRange('B6').values[0][0]-d.stats.mean)>1e-6) throw Error('Mean mismatch');
for(let i=0;i<d.rows.length;i++) if(JSON.stringify(s.getRangeByIndexes(i,0,1,22).values[0])!==JSON.stringify(d.rows[i])) throw Error(`Source mismatch ${i}`);
console.log((await w.inspect({kind:'table',range:'面积汇总!A1:B7',include:'values,formulas',tableMaxRows:7,tableMaxCols:2})).ndjson);
console.log((await w.inspect({kind:'match',searchTerm:'#REF!|#DIV/0!|#VALUE!|#NAME\\?|#NUM!',options:{useRegex:true,maxResults:10}})).ndjson);
for(const [sheet,range,file] of [[d.sheet,'V1:W8','hospital_after.png'],['面积汇总','A1:B14','hospital_summary.png']]) await fs.writeFile(`.codex_tmp/${file}`,new Uint8Array(await (await w.render({sheetName:sheet,range,scale:1.5})).arrayBuffer()));
await (await SpreadsheetFile.exportXlsx(w)).save(`${out}/baidu_maps_hospital_202608_sample_size.xlsx`);
console.log('Export complete');
